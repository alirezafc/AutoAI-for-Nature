import { getPost, updatePost, createPostRevision, type PostStatus } from "./posts";
import { getRunWithSteps, updateRun } from "./agent-runs";
import { startRegeneration } from "@/lib/agents/engine";
import { syncPublishedPostToKnowledge } from "@/lib/rag";
import { logAudit } from "./audit";

export type ReviewAction = "approve" | "reject" | "regenerate";

export interface ReviewResult {
  postId: string;
  status: string;
  reviewReason: string | null;
  runId: string | null;
  revisionId?: string;
  newRunId?: string;
  indexing?: { documentId: string; chunks: number; vectors: number } | { error: string };
}

export async function approveArticle(postId: string, actor = "admin"): Promise<ReviewResult> {
  const post = await getPost(postId);
  if (!post) throw new Error("Article not found");

  const rev = await createPostRevision(postId, {
    label: "Approved and published by human editor",
    actor,
    title: post.title,
    excerpt: post.excerpt,
    content: post.content,
  });

  await updatePost(
    postId,
    {
      status: "published" as PostStatus,
      reviewedAt: new Date(),
      reviewedBy: actor,
      reviewReason: null,
    },
    actor
  );

  // Publish -> Knowledge: index the article with the REAL embedding provider so
  // the chatbot retrieves the actual article as a source. Re-read AFTER the
  // status change so the sync always sees the published state and final
  // content. A failure here must be reported, never silently ignored.
  let indexing: ReviewResult["indexing"];
  try {
    const published = await getPost(postId);
    if (!published) throw new Error("Article disappeared during publish");
    indexing = await syncPublishedPostToKnowledge(published, `publish-${postId}`);
  } catch (err) {
    indexing = { error: err instanceof Error ? err.message : String(err) };
  }

  const run = post.agentRunId ? await getRunWithSteps(post.agentRunId) : null;
  if (run && run.status === "waiting_for_human") {
    await updateRun(run.id, { status: "completed", finishedAt: new Date() });
  }

  await logAudit({
    actor,
    action: "review.approved",
    target: postId,
    metadata: indexing && "error" in indexing ? { indexingError: indexing.error } : undefined,
  });

  return { postId, status: "published", reviewReason: null, runId: run?.id ?? null, revisionId: rev.id, indexing };
}

export async function rejectArticle(postId: string, reason: string, actor = "admin"): Promise<ReviewResult> {
  const post = await getPost(postId);
  if (!post) throw new Error("Article not found");

  const rev = await createPostRevision(postId, {
    label: "Rejected by human editor",
    actor,
    title: post.title,
    excerpt: post.excerpt,
    content: post.content,
    reason,
  });

  await updatePost(
    postId,
    {
      status: "rejected" as PostStatus,
      reviewedAt: new Date(),
      reviewedBy: actor,
      reviewReason: reason,
    },
    actor
  );

  const run = post.agentRunId ? await getRunWithSteps(post.agentRunId) : null;
  if (run && run.status === "waiting_for_human") {
    await updateRun(run.id, { status: "completed", finishedAt: new Date() });
  }

  await logAudit({ actor, action: "review.rejected", target: postId, metadata: { reason } });

  return { postId, status: "rejected", reviewReason: reason, runId: run?.id ?? null, revisionId: rev.id };
}

export async function regenerateArticle(
  postId: string,
  input: { language?: "en" | "fa"; categoryId?: string | null } = {},
  actor = "admin"
): Promise<ReviewResult> {
  const post = await getPost(postId);
  if (!post) throw new Error("Article not found");

  const { runId } = await startRegeneration({
    topic: post.title,
    language: input.language ?? (post.language as "en" | "fa") ?? "en",
    categoryId: input.categoryId ?? post.categoryId,
    postId,
  });

  const rev = await createPostRevision(postId, {
    label: "Regenerated by human editor — new agent run started",
    actor,
    title: post.title,
  });

  // Reset the post to a draft so it is clearly not published while regenerating.
  await updatePost(
    postId,
    {
      status: "draft" as PostStatus,
      reviewedAt: new Date(),
      reviewedBy: actor,
      reviewReason: null,
    },
    actor
  );

  await logAudit({ actor, action: "review.regenerated", target: postId, metadata: { runId } });

  // The new run is linked to this post, so the engine will overwrite it when it completes.
  return { postId, status: "draft", reviewReason: null, runId, revisionId: rev.id, newRunId: runId };
}